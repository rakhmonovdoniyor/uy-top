const I18nContext = createContext(null);

const CORRUPTED_TRANSLATION_PATTERN = /[\u3400-\u9fff\uf900-\ufaff]/;

function isCorruptedTranslation(value) {
  return typeof value === "string" && CORRUPTED_TRANSLATION_PATTERN.test(value);
}

function getSafeLocalizedValue({ fallbackLanguage = "en", language, source, key }) {
  const currentValue = source[language]?.[key];

  if (currentValue && !isCorruptedTranslation(currentValue)) {
    return currentValue;
  }

  if (language === "uz" && !source.uz?.[key]) {
    return key;
  }

  const fallbackValue = source[fallbackLanguage]?.[key];

  if (fallbackValue && !isCorruptedTranslation(fallbackValue)) {
    return fallbackValue;
  }

  const uzValue = source.uz?.[key];

  if (uzValue && !isCorruptedTranslation(uzValue)) {
    return uzValue;
  }

  return currentValue || fallbackValue || uzValue || key;
}

function getInitialLanguage() {
  if (typeof window === "undefined") {
    return "uz";
  }

  const savedLanguage = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);

  return languages.some((language) => language.code === savedLanguage)
    ? savedLanguage
    : "uz";
}

function interpolate(value, params = {}) {
  return Object.entries(params).reduce(
    (text, [key, replacement]) =>
      text.replaceAll(`{{${key}}}`, String(replacement)),
    value
  );
}

export function I18nProvider({ children }) {
  const [language, setLanguage] = useState(getInitialLanguage);

  useEffect(() => {
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo(
    () => ({
      language,
      languages,
      setLanguage,
      t(key, params) {
        const text = getSafeLocalizedValue({
          key,
          language,
          source: translations,
        });
        return interpolate(text, params);
      },
      tOption(value) {
        return getSafeLocalizedValue({
          key: value,
          language,
          source: staticValueTranslations,
        });
      },
    }),
    [language]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);

  if (!context) {
    throw new Error("useI18n must be used inside I18nProvider");
  }

  return context;
}
