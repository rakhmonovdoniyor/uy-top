import { useMemo } from "react";

export function useRealEstateAppState({
  admin,
  catalog,
  chat,
  compare,
  data,
  filters,
  listings,
  notifications,
  savedSearch,
  stats,
  user,
}) {
  return useMemo(
    () => ({
      adminActions: admin.adminActions,
      allListings: catalog.allListings,
      applyFilters: filters.applyFilters,
      chatConversations: chat.chatConversations,
      cities: catalog.cities,
      cleanupUploads: admin.cleanupUploads,
      clearCompareListings: compare.clearCompareListings,
      compareIds: compare.compareIds,
      createdListings: listings.createdListings,
      currentUser: user.currentUser,
      dataError: data.dataError,
      dataSource: data.dataSource,
      deleteListing: listings.deleteListing,
      deleteSavedSearch: savedSearch.deleteSavedSearch,
      districts: catalog.districts,
      favoriteIds: listings.favoriteIds,
      filters: filters.filters,
      isInitialLoading: data.isInitialLoading,
      listingReports: admin.listingReports,
      listingStatsById: stats.listingStatsById,
      markAllInboxMessagesRead: chat.markAllInboxMessagesRead,
      markAllNotificationsRead: notifications.markAllNotificationsRead,
      markConversationRead: chat.markConversationRead,
      markMessageRead: chat.markMessageRead,
      markNotificationRead: notifications.markNotificationRead,
      messages: chat.messages,
      notifications: notifications.notifications,
      reportListing: admin.reportListing,
      resetFilters: filters.resetFilters,
      resolveListingReport: admin.resolveListingReport,
      replyToMessage: chat.replyToMessage,
      savedSearches: savedSearch.savedSearches,
      saveSearch: savedSearch.saveSearch,
      searchSuggestions: catalog.searchSuggestions,
      sendChatMessage: chat.sendChatMessage,
      sendListingMessage: chat.sendListingMessage,
      startPhoneVerification: user.startPhoneVerification,
      toggleCompareListing: compare.toggleCompareListing,
      toggleFavorite: listings.toggleFavorite,
      toggleListingFeatured: listings.toggleListingFeatured,
      trackListingLead: stats.trackListingLead,
      trackListingView: stats.trackListingView,
      unreadChatCount: chat.unreadChatCount,
      updateFilter: filters.updateFilter,
      updateListingAdminNote: listings.updateListingAdminNote,
      updateListingModerationStatus: listings.updateListingModerationStatus,
      updateProfile: user.updateProfile,
      updateUserStatus: admin.updateUserStatus,
      users: user.users,
      verifyPhoneCode: user.verifyPhoneCode,
      visibleListings: catalog.visibleListings,
    }),
    [
      admin,
      catalog,
      chat,
      compare,
      data,
      filters,
      listings,
      notifications,
      savedSearch,
      stats,
      user,
    ]
  );
}
